"""Generates Unity editor stubs for EFT's scripts from serialized type trees dumped out of the game's bundles.

Unity binds a serialized MonoBehaviour to the game's class by assembly + namespace + class name, then reads fields by
name and layout. So a stub with the same identity and the same serialized fields (names, types, nesting) builds
bundles the game reads as its own components. Nested struct type names don't matter for serialization, so they're
generated per script (Owner_Type) to avoid clashes.

Usage: python -I gen_stubs.py script_types.json <out_dir>
"""
import json
import os
import sys

BASES = {
    'AnimationEventsStateBehaviour': 'StateMachineBehaviour',
    'LActionState': 'StateMachineBehaviour',
    'AnimatorControllerStaticData': 'ScriptableObject',
    'SoundBank': 'ScriptableObject',
}

PRIMITIVES = {
    'int': 'int', 'SInt32': 'int', 'UInt32': 'uint', 'SInt64': 'long', 'UInt64': 'ulong', 'SInt16': 'short',
    'UInt16': 'ushort', 'SInt8': 'sbyte', 'UInt8': 'byte', 'bool': 'bool', 'float': 'float', 'double': 'double',
    'char': 'char', 'string': 'string',
}

UNITY_STRUCTS = {
    'Vector2f': 'Vector2', 'Vector3f': 'Vector3', 'Vector4f': 'Vector4', 'Quaternionf': 'Quaternion',
    'ColorRGBA': 'Color', 'Rectf': 'Rect', 'Matrix4x4f': 'Matrix4x4', 'AnimationCurve': 'AnimationCurve',
    'Gradient': 'Gradient', 'BitField': 'LayerMask', 'AABB': 'Bounds',
}

UNITY_OBJECTS = {
    'GameObject', 'Transform', 'Component', 'Collider', 'Renderer', 'MeshRenderer', 'SkinnedMeshRenderer', 'Material',
    'Mesh', 'Texture', 'Texture2D', 'AudioClip', 'AnimationClip', 'RuntimeAnimatorController', 'Avatar', 'TextAsset',
    'ParticleSystem', 'Light', 'Animator', 'Shader', 'Sprite', 'Camera', 'Rigidbody', 'BoxCollider',
    'AudioMixerGroup', 'ScriptableObject', 'MonoBehaviour', 'Object',
}


class Node:
    def __init__(self, d):
        self.depth, self.type, self.name, self.flags = d['d'], d['type'], d['name'], d['flags']
        self.children = []


def build(nodes):
    root = Node(nodes[0])
    stack = [root]
    for raw in nodes[1:]:
        n = Node(raw)
        while stack[-1].depth >= n.depth:
            stack.pop()
        stack[-1].children.append(n)
        stack.append(n)
    return root


class Gen:
    def __init__(self, owner, known_scripts):
        self.owner = owner
        self.known = known_scripts
        self.nested = {}  # generated name -> code

    def type_of(self, n):
        """C# type for a field node."""
        t = n.type
        if t.startswith('PPtr<'):
            target = t[5:-1].lstrip('$')
            if target in UNITY_OBJECTS:
                return target if target != 'Object' else 'UnityEngine.Object'
            if target in self.known:
                return self.known[target]
            return 'UnityEngine.Object'
        if t in PRIMITIVES and not n.children or t == 'string':
            return PRIMITIVES[t]
        if t in UNITY_STRUCTS:
            return UNITY_STRUCTS[t]
        # vector<T> / staticvector / arrays: a node whose child is "Array"
        arr = next((c for c in n.children if c.type == 'Array'), None)
        if arr is not None:
            data = next(c for c in arr.children if c.name == 'data')
            return 'List<%s>' % self.type_of(data)
        if t == 'map' or t == 'pair':
            return None  # Unity doesn't serialize dictionaries; never seen in these scripts
        # a nested serializable class/struct
        name = '%s_%s' % (self.owner, t)
        if name not in self.nested:
            self.nested[name] = None  # placeholder against recursion
            self.nested[name] = self.cls(name, n.children, '[Serializable]\n    public class %s' % name)
        return name

    def fields(self, children):
        lines = []
        for c in children:
            ct = self.type_of(c)
            if ct is None:
                lines.append('        // skipped %s %s' % (c.type, c.name))
                continue
            lines.append('        public %s %s;' % (ct, c.name))
        return lines

    def cls(self, name, children, header):
        return '    %s\n    {\n%s\n    }\n' % (header, '\n'.join(self.fields(children)))


def main():
    types = json.load(open(sys.argv[1]))
    out_dir = sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    known = {k: (v['ns'] + '.' + k if v['ns'] else k) for k, v in types.items()}
    for script, info in sorted(types.items()):
        root = build(info['nodes'])
        own = [c for c in root.children if c.name not in ('m_GameObject', 'm_Enabled', 'm_Script', 'm_Name')]
        g = Gen(script, known)
        body = g.cls(script, own, 'public class %s : %s' % (script, BASES.get(script, 'MonoBehaviour')))
        nested = '\n'.join(v for v in g.nested.values() if v)
        code = ('// Generated by tools/gen_stubs.py from the game\'s serialized type tree. Do not edit by hand.\n'
                'using System;\nusing System.Collections.Generic;\nusing UnityEngine;\n\n')
        ns = info['ns']
        inner = body + ('\n' + nested if nested else '')
        if ns:
            code += 'namespace %s\n{\n%s}\n' % (ns, inner)
        else:
            code += inner.replace('\n    ', '\n')[4:] if inner.startswith('    ') else inner
        with open(os.path.join(out_dir, script + '.cs'), 'w', encoding='utf-8') as f:
            f.write(code)
        print('wrote', script, '(%d nested)' % len([v for v in g.nested.values() if v]))


if __name__ == '__main__':
    main()
